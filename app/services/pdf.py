from typing import Any

import weasyprint

_TYPE_BADGE_COLORS = {
    "bug": "#dc2626",
    "feature": "#4f46e5",
}
_DEFAULT_BADGE_COLOR = "#6b7280"


def _render_transcript(transcript: list[dict[str, Any]]) -> str:
    if not transcript:
        return '<p class="empty">No data available</p>'

    rows = []
    for segment in transcript:
        speaker = segment.get("speaker", "Unknown")
        timestamp = segment.get("timestamp", "")
        text = segment.get("text", "")
        rows.append(
            f"""
            <div class="segment">
                <div class="segment-meta">
                    <span class="speaker">Speaker {speaker}</span>
                    <span class="timestamp">{timestamp}</span>
                </div>
                <p class="segment-text" style="text-align: justify;">{text}</p>
            </div>
            """
        )
    return "".join(rows)


def _render_action_items(action_items: list[dict[str, Any]]) -> str:
    if not action_items:
        return '<p class="empty">No data available</p>'

    rows = []
    for item in action_items:
        item_type = item.get("type", "")
        badge_color = _TYPE_BADGE_COLORS.get(item_type, _DEFAULT_BADGE_COLOR)
        title = item.get("title", "")
        description = item.get("description", "")
        prompt = item.get("prompt", "")
        rows.append(
            f"""
            <div class="action-item">
                <span class="badge" style="background-color: {badge_color};">{item_type or "other"}</span>
                <p class="item-title">{title}</p>
                <p class="item-description">{description}</p>
                <div class="prompt-box">{prompt}</div>
            </div>
            """
        )
    return "".join(rows)


